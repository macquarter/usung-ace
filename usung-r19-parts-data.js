  function pick(m) {
    var cat = m.cat || '', mid = m.mid || '', grp = m.grp || '';
    if (cat === '갤럭시') {
      var side = grp.indexOf('양옆태엽') >= 0, inner = grp.indexOf('내부태엽') >= 0;
      if (mid === '갤럭시A') return [inner ? 'GA_I' : 'GA_S', 'gal'];
      if (mid === '갤럭시B') {
        if (grp.indexOf('304스텐-90') === 0) return ['GB_N', 'gal'];
        return [inner ? 'GB_I' : 'GB_S', 'gal'];
      }
      if (mid === '갤럭시C') return [inner ? 'GC_I' : 'GC_S', 'gal'];
      if (mid === '갤럭시D') return [grp.indexOf('갓등') >= 0 ? 'GD_L' : 'GD_P', 'gal'];
      return [side || inner ? 'GA_S' : 'GA_S', 'gal'];
    }
    if (cat === 'LED조명') return [mid === '디자인등' ? 'LED_D' : 'LED_M', 'led'];
    if (cat === '파이프') return mid === '내부태엽' ? ['PIPE_I', 'pipeI'] : ['PIPE_S', 'pipe'];
    if (cat === '후레쉬볼') {
      if (mid.indexOf('갓 자바라') >= 0) return [null, 'ballL'];   // 「갓자바라는 부품 없이 그냥 제품만」
      if (mid.indexOf('장축') >= 0) return ['BALL_L', 'ballL'];
      return ['BALL_J', 'ballJ'];
    }
    if (cat === '코브라후드') return [COB[grp] || null, 'cob'];
    return [null, 'pipe'];
  }

